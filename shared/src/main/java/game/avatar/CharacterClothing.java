package game.avatar;

public class CharacterClothing {

    private String upperType = "shirt";
    private String upperColor = "#171616";

    private String outerType = "none";
    private String outerColor = "#000000";

    private String pantsType = "pants";
    private String pantsColor = "#303C47";

    private String shoesType = "boots";
    private String shoesColor = "#171514";

    public String getUpperType() {
        return upperType;
    }

    public void setUpperType(String upperType) {
        this.upperType = upperType;
    }

    public String getUpperColor() {
        return upperColor;
    }

    public void setUpperColor(String upperColor) {
        this.upperColor = upperColor;
    }

    public String getOuterType() {
        return outerType;
    }

    public void setOuterType(String outerType) {
        this.outerType = outerType;
    }

    public String getOuterColor() {
        return outerColor;
    }

    public void setOuterColor(String outerColor) {
        this.outerColor = outerColor;
    }

    public String getPantsType() {
        return pantsType;
    }

    public void setPantsType(String pantsType) {
        this.pantsType = pantsType;
    }

    public String getPantsColor() {
        return pantsColor;
    }

    public void setPantsColor(String pantsColor) {
        this.pantsColor = pantsColor;
    }

    public String getShoesType() {
        return shoesType;
    }

    public void setShoesType(String shoesType) {
        this.shoesType = shoesType;
    }

    public String getShoesColor() {
        return shoesColor;
    }

    public void setShoesColor(String shoesColor) {
        this.shoesColor = shoesColor;
    }
}